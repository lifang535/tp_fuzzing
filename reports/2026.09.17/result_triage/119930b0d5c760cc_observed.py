def _finite_compare(C, ref, check_signed_zero=False):
    """Check exceptional values before measuring finite numerical error.

    Reference results are rounded to the declared output storage dtype. Matching
    NaNs are allowed; a NaN/Inf introduced or lost by the kernel is not.
    """
    import torch
    if C.shape != ref.shape:
        raise RuntimeError(f"WRONG RESULT: shape {tuple(C.shape)} != {tuple(ref.shape)}")
    # Bound temporary memory for the very large shapes generated by the fuzzer.
    # Float64 differences avoid overflowing while subtracting finite fp32 values.
    actual = C.reshape(-1)
    expected = ref.reshape(-1)
    max_error = torch.zeros((), dtype=torch.float64, device=C.device)
    magnitude_sum = torch.zeros_like(max_error)
    finite_count = torch.zeros((), dtype=torch.int64, device=C.device)
    for start in range(0, actual.numel(), 1 << 20):
        c = actual[start:start + (1 << 20)].to(torch.float64)
        r = expected[start:start + (1 << 20)].to(dtype=C.dtype, device=C.device).to(torch.float64)
        if not torch.equal(torch.isnan(c), torch.isnan(r)):
            raise RuntimeError("WRONG RESULT: NaN locations differ")
        if not torch.equal(torch.isposinf(c), torch.isposinf(r)) or not torch.equal(torch.isneginf(c), torch.isneginf(r)):
            raise RuntimeError("WRONG RESULT: infinity locations or signs differ")
        if check_signed_zero:
            zeros = (c == 0) & (r == 0)
            if not torch.equal(torch.signbit(c[zeros]), torch.signbit(r[zeros])):
                raise RuntimeError("WRONG RESULT: signed zeros differ")
        mask = torch.isfinite(c) & torch.isfinite(r)
        max_error = torch.maximum(max_error, torch.where(mask, (c - r).abs(), 0.0).max())
        magnitude_sum += torch.where(mask, r.abs(), 0.0).sum()
        finite_count += mask.sum()
    count = finite_count.item()
    if count == 0:
        return 0.0, 1.0, 0.0
    max_diff = max_error.item()
    ref_norm = magnitude_sum.item() / count + 1e-6
    return max_diff, ref_norm, max_diff / ref_norm

def _max_diff(C, ref, check_signed_zero=False):
    return _finite_compare(C, ref, check_signed_zero=check_signed_zero)[0]

def _region_reference(A, B, body, block_m, block_n, output_dtype, functions=()):
    import torch
    m = A.shape[0]
    n = B.shape[1] if body['operations'][0]['kind'] == 'gemm' else A.shape[1]
    pm, pn = (m + block_m - 1) // block_m * block_m, (n + block_n - 1) // block_n * block_n
    by = torch.arange(pm, device=A.device) // block_m
    bx = torch.arange(pn, device=A.device) // block_n
    function_pool = {fn['name']: fn['body'] for fn in functions}
    def padded(x):
        return torch.nn.functional.pad(x, (0, pn - n, 0, pm - m))
    def tile_index(axis, iteration):
        if axis == 'row':
            return by[:, None]
        if axis == 'column':
            return bx[None, :]
        if axis == 'checkerboard':
            return by[:, None] + bx[None, :]
        return torch.tensor(iteration, device=A.device)
    def execute(region, parent, argument=None, iteration=0):
        values = dict(parent)
        if region['arguments']:
            values[region['arguments'][0]] = argument
        for op in region['operations']:
            kind, attrs = op['kind'], op['attrs']
            args = [values[v] for v in op['operands']]
            if kind == 'load':
                result = padded(A.float())
            elif kind == 'gemm':
                result = padded(A.float() @ B.float())
            elif kind == 'call':
                callee = function_pool[attrs['callee']]
                # A callee sees only its own formal arguments, never caller locals.
                bindings = dict(zip(callee['arguments'], args))
                result = execute({**callee, 'arguments': []}, bindings, iteration=iteration)
            elif kind == 'index_add':
                index = tile_index(attrs['axis'], iteration)
                result = args[0] + index * attrs['scale']
            elif kind == 'scale':
                result = args[0] * attrs['alpha']
            elif kind == 'neg':
                result = -args[0]
            elif kind == 'abs':
                result = args[0].abs()
            elif kind == 'sqrt':
                result = args[0].abs().sqrt()
            elif kind == 'round':
                result = args[0].to(getattr(torch, attrs['dtype'])).float()
            elif kind == 'add':
                result = args[0] + args[1]
            elif kind == 'mul':
                result = args[0] * args[1]
            elif kind == 'copy':
                result = args[0].clone()
            elif kind == 'exp':
                result = args[0].clamp(-10, 10).exp()
            elif kind == 'sub':
                result = args[0] - args[1]
            elif kind == 'maximum':
                result = torch.maximum(args[0], args[1])
            elif kind == 'minimum':
                result = torch.minimum(args[0], args[1])
            elif kind == 'div':
                # Defined division avoids trivial zero-denominator failures.
                result = args[0] / args[1].abs().clamp_min(1e-3)
            elif kind == 'where':
                result = torch.where(args[0] > 0, args[1], args[2])
            elif kind == 'tile_transpose':
                result = args[0].reshape(pm//block_m, block_m, pn//block_n, block_n).permute(0, 3, 2, 1).reshape(pm, pn)
            elif kind.startswith('row_'):
                tiles = args[0].reshape(pm, pn//block_n, block_n)
                if kind == 'row_softmax':
                    result = tiles.softmax(-1).reshape(pm, pn)
                else:
                    fn = {'row_sum': 'sum', 'row_max': 'amax', 'row_min': 'amin'}[kind]
                    result = getattr(tiles, fn)(-1, keepdim=True).expand_as(tiles).reshape(pm, pn)
            elif kind == 'for':
                result = args[0]
                for i in range(attrs['trip_count']):
                    index = attrs.get('start', 0) + i * attrs.get('step', 1)
                    result = execute(op['regions'][0], values, result, iteration=index)
            elif kind == 'if':
                left = execute(op['regions'][0], values, args[0], iteration)
                right = execute(op['regions'][1], values, args[0], iteration)
                index = tile_index(attrs.get('predicate', 'row'), iteration)
                result = torch.where(index % attrs.get('modulus', 2) == attrs['parity'], left, right)
            else:
                raise ValueError('Unsupported region reference operation: ' + kind)
            values[op['result']] = result
        return values[region['yield_value']]
    return execute(body, {})[:m, :n].to(getattr(torch, output_dtype))

def matrix_layout(rows, cols, layout):
    """Return element strides, base offset and storage size including a guard."""
    if rows < 1 or cols < 1:
        raise ValueError('Matrix dimensions must be positive')
    if layout == 'contiguous':
        stride_row, stride_col, offset = cols, 1, 0
    elif layout == 'transposed':
        stride_row, stride_col, offset = 1, rows, 0
    elif layout == 'strided':
        stride_row, stride_col, offset = 2 * cols + 3, 2, 0
    elif layout == 'offset':
        stride_row, stride_col, offset = cols + 3, 1, 7
    elif layout == 'broadcast_rows':
        stride_row, stride_col, offset = 0, 1, 0
    elif layout == 'broadcast_cols':
        stride_row, stride_col, offset = 1, 0, 0
    else:
        raise ValueError('Unsupported matrix layout: ' + layout)
    size = offset + (rows - 1) * stride_row + (cols - 1) * stride_col + 17
    return stride_row, stride_col, offset, size

def _region_input(shape, dtype, pattern, scale, device='cuda'):
    import torch
    if pattern == 'normal':
        value = torch.randn(shape, dtype=dtype, device=device)
    elif pattern == 'integer':
        value = torch.randint(-3, 4, shape, device=device).to(dtype)
    elif pattern == 'alternating':
        # Signed, exactly representable values exercise cancellation and zeros.
        phase = torch.randint(0, 4, (), device=device)
        value = ((torch.arange(shape[0] * shape[1], device=device) + phase) % 4 - 2).reshape(shape).to(dtype)
    else:
        raise ValueError('Unknown region input pattern: ' + pattern)
    return value * scale

def _region_input_storage(shape, dtype, pattern, scale, layout, device='cuda'):
    """Initialize unique addresses; retain padding for input-integrity checks."""
    import torch
    rows, cols = shape
    stride_row, stride_col, offset, size = matrix_layout(rows, cols, layout)
    storage = torch.full((size,), 19, dtype=dtype, device=device)
    view = storage.as_strided(shape, (stride_row, stride_col), offset)
    # Broadcast views overlap: never copy an entire matrix into those views.
    if layout == 'broadcast_rows':
        view[0].copy_(_region_input((1, cols), dtype, pattern, scale, device)[0])
    elif layout == 'broadcast_cols':
        view[:, 0].copy_(_region_input((rows, 1), dtype, pattern, scale, device)[:, 0])
    else:
        view.copy_(_region_input(shape, dtype, pattern, scale, device))
    return storage, view

def _region_equal(actual, expected, label):
    import torch
    if not torch.equal(actual.contiguous().view(torch.uint8), expected.contiguous().view(torch.uint8)):
        raise RuntimeError('WRONG RESULT: ' + label)

def _region_check(actual, expected, relative, tolerance, label):
    try:
        maximum, _, normalized = _finite_compare(actual, expected)
    except RuntimeError as error:
        raise RuntimeError(f'WRONG RESULT: {label}: {error}') from error
    error = normalized if relative else maximum
    if error > tolerance:
        raise RuntimeError(f'WRONG RESULT: {label}: error={error}, tolerance={tolerance}')

def _run_region(launches, inputs, reference, repeats, tolerance, relative=False):
    """Each factory prepares a schedule after the previous schedule has run.

    The caller computes reference before any target kernel can corrupt inputs.
    Tile geometry stays fixed across schedules, preserving tile-local semantics.
    """
    import torch
    if repeats < 1 or not launches:
        raise ValueError('Region execution requires a launch and positive repeats')
    guard = 16
    output = torch.full((reference.numel() + 2 * guard,), 23,
                        dtype=reference.dtype, device=reference.device)
    actual = output[guard:-guard].view_as(reference)
    snapshots = [tensor.clone() for tensor in inputs]
    reference_nan = torch.isnan(reference)
    baseline = None
    for variant, prepare in enumerate(launches):
        launch = prepare()
        for repeat in range(repeats):
            output.fill_(23)
            # Missing writes must fail even if the expected value itself is NaN.
            actual.fill_(float('nan'))
            actual.masked_fill_(reference_nan, 0.0)
            launch(actual)
            if reference.is_cuda:
                torch.cuda.synchronize(reference.device)
            if not torch.all(output[:guard] == 23) or not torch.all(output[-guard:] == 23):
                raise RuntimeError(f'WRONG RESULT: output canary modified (schedule={variant})')
            for tensor, snapshot in zip(inputs, snapshots):
                _region_equal(tensor, snapshot, 'input storage modified')
            if repeat == 0:
                if baseline is None:
                    baseline = actual.clone()
                    repeat_baseline = baseline
                else:
                    _region_check(actual, baseline, relative, tolerance, 'schedule invariance')
                    repeat_baseline = actual.clone()
            else:
                _region_equal(actual, repeat_baseline, 'repeat determinism')
            _region_check(actual, reference, relative, tolerance, 'structured reference')

